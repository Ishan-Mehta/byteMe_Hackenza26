def train():
    drive.mount('/content/drive')

    DRIVE_BASE  = "/content/drive/My Drive/hackenza-2026-test-time-adaptation-in-the-wild"
    SOURCE_PATH = os.path.join(DRIVE_BASE, "source_toxic.pt")
    SAVE_PATH   = "/content/drive/My Drive/weights_v2.pth"

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"Training on: {device}")

    data   = torch.load(SOURCE_PATH)
    images = data['images'].float() / 255.0
    labels = data['labels'].long()
    print(f"Loaded {len(images)} training samples")

    EPOCHS     = 80
    BATCH_SIZE = 128
    LR         = 1e-3

    dataset   = AugmentedDataset(images, labels, augment_prob=0.8)
    loader    = DataLoader(dataset, batch_size=BATCH_SIZE,
                           shuffle=True, drop_last=True, num_workers=2)

    model     = RobustClassifier(num_classes=10).to(device)
    criterion = GCELoss(q=0.7)
    optimizer = optim.Adam(model.parameters(), lr=LR, weight_decay=1e-4)
    scheduler = CosineAnnealingLR(optimizer, T_max=EPOCHS)

    best_loss = float('inf')

    for epoch in range(EPOCHS):
        model.train()
        total_loss, correct, total = 0, 0, 0

        for inputs, targets in loader:
            inputs, targets = inputs.to(device), targets.to(device)
            optimizer.zero_grad()
            outputs = model(inputs)
            loss    = criterion(outputs, targets)
            loss.backward()
            optimizer.step()

            total_loss += loss.item()
            _, predicted = outputs.max(1)
            total   += targets.size(0)
            correct += predicted.eq(targets).sum().item()

        scheduler.step()
        epoch_loss = total_loss / len(loader)
        epoch_acc  = 100. * correct / total
        print(f"Epoch [{epoch+1}/{EPOCHS}] | Loss: {epoch_loss:.4f} | Acc: {epoch_acc:.2f}%")

        if epoch_loss < best_loss:
            best_loss = epoch_loss
            torch.save(model.state_dict(), SAVE_PATH)

    print(f"\nDone. Best weights saved to {SAVE_PATH}")
    print("Update WEIGHTS_PATH in estimate_shift.py and adapt.py to weights_v2.pth")


if __name__ == "__main__":
    torch.manual_seed(42)
    np.random.seed(42)
    random.seed(42)
    train()

