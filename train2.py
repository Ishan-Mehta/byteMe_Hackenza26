class PermittedAugment:
    """
    Whitelist only:
      - Random horizontal flip
      - Random crop with padding
      - Random rotation / affine
      - ColorJitter (brightness/contrast)
      - Cutout (random erasing)
    """

    def random_flip(self, x):
        if random.random() < 0.5:
            return torch.flip(x, dims=[2])
        return x

    def random_crop(self, x):
        pad = 4
        x_padded = F.pad(x.unsqueeze(0), (pad, pad, pad, pad), mode='reflect').squeeze(0)
        i = random.randint(0, 2 * pad - 1)
        j = random.randint(0, 2 * pad - 1)
        return x_padded[:, i:i+28, j:j+28]

    def random_rotation(self, x):
        angle = random.uniform(-15, 15) * (3.14159 / 180.0)
        cos_a, sin_a = float(np.cos(angle)), float(np.sin(angle))
        theta = torch.tensor([[cos_a, -sin_a, 0.0],
                               [sin_a,  cos_a, 0.0]], dtype=torch.float32)
        grid = F.affine_grid(theta.unsqueeze(0),
                             x.unsqueeze(0).size(),
                             align_corners=False)
        return F.grid_sample(x.unsqueeze(0), grid,
                             align_corners=False,
                             padding_mode='reflection').squeeze(0)

    def color_jitter(self, x):
        brightness = random.uniform(0.7, 1.3)
        contrast   = random.uniform(0.7, 1.3)
        mean = x.mean()
        x = (x * brightness).clamp(0, 1)
        x = ((x - mean) * contrast + mean).clamp(0, 1)
        return x

    def cutout(self, x, length=8):
        h, w = x.shape[1], x.shape[2]
        y  = random.randint(0, h - 1)
        cx = random.randint(0, w - 1)
        y1, y2 = max(0, y - length // 2), min(h, y + length // 2)
        x1, x2 = max(0, cx - length // 2), min(w, cx + length // 2)
        x = x.clone()
        x[:, y1:y2, x1:x2] = 0.0
        return x

    def __call__(self, x):
        x = self.random_flip(x)
        x = self.random_crop(x)
        if random.random() < 0.5:
            x = self.random_rotation(x)
        if random.random() < 0.5:
            x = self.color_jitter(x)
        if random.random() < 0.4:
            x = self.cutout(x)
        return x


class AugmentedDataset(Dataset):
    def __init__(self, images, labels, augment_prob=0.8):
        self.images       = images
        self.labels       = labels
        self.augment      = PermittedAugment()
        self.augment_prob = augment_prob

    def __len__(self):
        return len(self.images)

    def __getitem__(self, idx):
        x = self.images[idx].clone()
        y = self.labels[idx]
        if random.random() < self.augment_prob:
            x = self.augment(x)
        return x, y


